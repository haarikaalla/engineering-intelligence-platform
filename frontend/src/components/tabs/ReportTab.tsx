"use client";

import { useMemo, useState } from "react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { Download, FileCheck2, Info, Loader2, ShieldCheck, Sparkles } from "lucide-react";
import { post, useApi } from "@/lib/api";
import { CodeViewer, EvidenceChip, type Evidence } from "@/components/CodeViewer";
import { Badge, Card, ErrorBox, Spinner } from "@/components/ui";

interface Fact {
  id: string;
  text: string;
  evidence: Evidence[];
  kind: "fact" | "quote" | "inference" | "metric";
}

interface Report {
  repository: string;
  sections: { id: string; title: string; intro?: string; facts: string[] }[];
  facts: Record<string, Fact>;
  limitations: string[];
  stats: { facts: number; files_cited: number; evidence_backed: number; metric_facts: number };
  narrative?: Narrative;
}

interface Narrative {
  text: string;
  cited_facts: string[];
  dropped_unsupported: string[];
  mentions: { verified: string[]; unverified: string[]; score: number };
  model?: string;
}

const KIND_TONE: Record<string, string | undefined> = { quote: "low", inference: "medium", metric: "info" };

function InlineMd({ text }: { text: string }) {
  return (
    <ReactMarkdown remarkPlugins={[remarkGfm]} components={{ p: ({ children }) => <span>{children}</span> }}>
      {text}
    </ReactMarkdown>
  );
}

export function ReportTab({ repoId }: { repoId: string }) {
  const { data, error, loading, setData } = useApi<Report>(`/repositories/${repoId}/report`);
  const [open, setOpen] = useState<Evidence | null>(null);
  const [busy, setBusy] = useState(false);
  const [narrError, setNarrError] = useState<string | null>(null);
  const [filter, setFilter] = useState("");

  const visible = useMemo(() => {
    if (!data) return [];
    const q = filter.toLowerCase();
    return data.sections
      .map((s) => ({ ...s, facts: s.facts.filter((id) => !q || data.facts[id].text.toLowerCase().includes(q) || data.facts[id].evidence.some((e) => e.path.toLowerCase().includes(q))) }))
      .filter((s) => s.facts.length);
  }, [data, filter]);

  async function generateNarrative() {
    setBusy(true);
    setNarrError(null);
    try {
      const n = await post<Narrative>(`/repositories/${repoId}/report/narrative`, {});
      setData((d) => (d ? { ...d, narrative: n } : d));
    } catch (e) {
      setNarrError((e as Error).message);
    } finally {
      setBusy(false);
    }
  }

  async function download() {
    const res = await fetch(`/api/repositories/${repoId}/report/markdown`);
    const blob = await res.blob();
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${data?.repository.replace(/[^\w.-]+/g, "_") ?? "repository"}-report.md`;
    a.click();
    URL.revokeObjectURL(url);
  }

  if (loading) return <Spinner label="Building evidence report…" />;
  if (error) return <ErrorBox message={error} />;
  if (!data) return null;

  const narrativeMd = data.narrative?.text.replace(/\[(F\d+)\]/g, "[$1](#fact-$1)");

  return (
    <div className="grid gap-5 lg:grid-cols-[240px_1fr]">
      <aside className="lg:sticky lg:top-4 lg:self-start">
        <div className="card p-4 text-sm">
          <div className="card-title mb-2">Contents</div>
          <ul className="space-y-1">
            {data.narrative && (
              <li>
                <a href="#sec-narrative" className="hover:text-brand-600">AI narrative</a>
              </li>
            )}
            {visible.map((s) => (
              <li key={s.id}>
                <a href={`#sec-${s.id}`} className="flex justify-between hover:text-brand-600">
                  <span>{s.title}</span> <span className="text-xs text-slate-400">{s.facts.length}</span>
                </a>
              </li>
            ))}
            <li>
              <a href="#sec-limitations" className="hover:text-brand-600">Limitations</a>
            </li>
          </ul>
        </div>
      </aside>

      <div className="space-y-5">
        <Card>
          <div className="flex flex-wrap items-start justify-between gap-4">
            <div>
              <h2 className="flex items-center gap-2 text-lg font-bold text-slate-900">
                <ShieldCheck className="h-5 w-5 text-emerald-600" /> Evidence-backed repository report
              </h2>
              <p className="mt-1 max-w-3xl text-sm text-slate-500">
                Every statement is extracted from the source code, manifests or configuration and links to the exact file and line. Click a chip to see the
                code. Nothing here is generated by an LLM; what could not be determined is listed under Limitations.
              </p>
              <div className="mt-2 flex flex-wrap gap-2 text-xs">
                <Badge tone="low">{data.stats.facts} facts</Badge>
                <Badge tone="low">{data.stats.evidence_backed} with code evidence</Badge>
                <Badge>{data.stats.files_cited} files cited</Badge>
                <Badge tone="info">{data.stats.metric_facts} computed metrics</Badge>
              </div>
            </div>
            <div className="flex flex-col gap-2">
              <button className="btn-secondary" onClick={() => void download()}>
                <Download className="h-4 w-4" /> Download Markdown
              </button>
              <button className="btn-primary" onClick={() => void generateNarrative()} disabled={busy}>
                {busy ? <Loader2 className="h-4 w-4 animate-spin" /> : <Sparkles className="h-4 w-4" />} Grounded AI narrative
              </button>
            </div>
          </div>
          <input className="input mt-4" placeholder="Filter facts by text or file…" value={filter} onChange={(e) => setFilter(e.target.value)} />
          {narrError && <div className="mt-3"><ErrorBox message={narrError} /></div>}
        </Card>

        {data.narrative && (
          <section id="sec-narrative">
            <Card title={<span className="flex items-center gap-2"><Sparkles className="h-4 w-4" /> AI narrative — restricted to the facts below</span>}>
              <div className="mb-3 flex flex-wrap gap-2 text-xs">
                <Badge tone="low">{data.narrative.cited_facts.length} facts cited</Badge>
                <Badge tone={data.narrative.mentions.unverified.length ? "high" : "low"}>code references verified: {data.narrative.mentions.score}%</Badge>
                {data.narrative.dropped_unsupported.length > 0 && <Badge tone="medium">{data.narrative.dropped_unsupported.length} unsupported sentences removed</Badge>}
                {data.narrative.model && <Badge>{data.narrative.model}</Badge>}
              </div>
              <div className="markdown text-sm">
                <ReactMarkdown
                  remarkPlugins={[remarkGfm]}
                  components={{
                    a: ({ href, children }) => {
                      const fid = href?.startsWith("#fact-") ? href.slice(6) : null;
                      const fact = fid ? data.facts[fid] : null;
                      if (!fact) return <a href={href}>{children}</a>;
                      return (
                        <button
                          title={fact.text}
                          className="mx-0.5 rounded bg-emerald-50 px-1 font-mono text-[10px] text-emerald-700 hover:bg-emerald-100"
                          onClick={() => fact.evidence[0] && setOpen(fact.evidence[0])}
                        >
                          {fid}
                        </button>
                      );
                    },
                  }}
                >
                  {narrativeMd ?? ""}
                </ReactMarkdown>
              </div>
              {data.narrative.mentions.unverified.length > 0 && (
                <div className="mt-3 rounded bg-red-50 p-2 text-xs text-red-700">
                  Not found in this repository (treat as unverified): {data.narrative.mentions.unverified.join(", ")}
                </div>
              )}
              {data.narrative.dropped_unsupported.length > 0 && (
                <details className="mt-2 text-xs text-slate-500">
                  <summary className="cursor-pointer">Removed sentences without supporting facts</summary>
                  <ul className="mt-1 list-disc pl-5">
                    {data.narrative.dropped_unsupported.map((s) => <li key={s}>{s}</li>)}
                  </ul>
                </details>
              )}
            </Card>
          </section>
        )}

        {visible.map((s) => (
          <section key={s.id} id={`sec-${s.id}`}>
            <Card title={s.title}>
              {s.intro && <p className="-mt-2 mb-3 text-xs text-slate-400">{s.intro}</p>}
              <ul className="divide-y divide-slate-100">
                {s.facts.map((id) => {
                  const f = data.facts[id];
                  return (
                    <li key={id} id={`fact-${id}`} className="flex flex-wrap items-start gap-2 py-2 text-sm">
                      <span className="mt-0.5 w-10 shrink-0 font-mono text-[10px] text-slate-400">{id}</span>
                      <div className="min-w-0 flex-1 text-slate-700 [&_code]:rounded [&_code]:bg-slate-100 [&_code]:px-1 [&_code]:font-mono [&_code]:text-[0.85em] [&_code]:text-brand-700">
                        <InlineMd text={f.text} />
                        <div className="mt-1 flex flex-wrap items-center gap-1">
                          {f.kind !== "fact" && <Badge tone={KIND_TONE[f.kind]}>{f.kind}</Badge>}
                          {f.evidence.map((e) => <EvidenceChip key={`${e.path}:${e.line}`} e={e} onOpen={setOpen} />)}
                        </div>
                      </div>
                    </li>
                  );
                })}
              </ul>
            </Card>
          </section>
        ))}

        <section id="sec-limitations">
          <Card title={<span className="flex items-center gap-2"><Info className="h-4 w-4" /> Limitations — what could not be determined</span>}>
            <ul className="list-disc space-y-1 pl-5 text-sm text-slate-600">
              {data.limitations.map((l) => <li key={l}>{l}</li>)}
            </ul>
            <p className="mt-3 flex items-center gap-1 text-xs text-slate-400">
              <FileCheck2 className="h-3.5 w-3.5" /> Legend: <Badge>fact</Badge> extracted from code · <Badge tone="low">quote</Badge> verbatim from docs ·
              <Badge tone="medium">inference</Badge> derived from multiple signals · <Badge tone="info">metric</Badge> computed
            </p>
          </Card>
        </section>
      </div>

      {open && <CodeViewer repoId={repoId} evidence={open} onClose={() => setOpen(null)} />}
    </div>
  );
}
